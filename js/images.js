// Copy image to clipboard function.
async function copyCanvasImageToClipboard(canvasElement) {
  try {
    // 1. Get the image data as a Blob from the canvas
    const blob = await new Promise(resolve => canvasElement.toBlob(resolve, 'image/png'));

    // 2. Create a ClipboardItem with the image Blob
    const clipboardItem = new ClipboardItem({
      [blob.type]: blob
    });

    // 3. Write the ClipboardItem to the clipboard
    await navigator.clipboard.write([clipboardItem]);

    console.log('Image copied to clipboard!');
    showToast('Copied to clipboard');
  } catch (err) {
    console.error('Failed to copy image:', err);
  }
}

// Draw an overlay label PNG in the bottom-right, sized to its own aspect ratio.
// `scale` multiplies the base width (canvas.width / 8).
function drawOverlayLabel(src, margin, scale = 1) {
  return new Promise((resolve) => {
    const overlay = new Image();
    overlay.onload = () => {
      const w = (canvas.width / 8) * scale;
      const h = w * (overlay.naturalHeight / overlay.naturalWidth); // preserve label aspect
      ctx.drawImage(overlay, canvas.width - w - margin, canvas.height - h - margin, w, h);
      resolve();
    };
    overlay.onerror = () => { console.error('Could not load overlay label:', src); resolve(); };
    overlay.src = src;
  });
}

// The chosen ai-label.org banner. `variant` is one of 'made-with-ai' | 'assisted-by-ai' | 'no-ai-used'.
function drawAiLabelBanner(variant, margin) {
  return drawOverlayLabel(`ai-label/ai-label_banner-${variant}.png`, margin);
}

// The chosen EU label. `variant` is a filename stem, e.g. 'AI GENERATED_black'.
function drawEuLabel(variant, margin) {
  return drawOverlayLabel(encodeURI(`eu-labels/LABEL_${variant} transparent.png`), margin, 1.4);
}

// Label It button.
labelButton.addEventListener('click', async () => {
const selectedOption = Array.from(labelOptions).find(option => option.checked).value;
const fontSize = canvas.width / 30;

// Redraw the clean base image first so labels don't stack on repeated clicks.
ctx.drawImage(image, 0, 0);

if (selectedOption === 'ai-label') {
  await drawAiLabelBanner(aiLabelDropdown.value, fontSize);
} else if (selectedOption === 'eu-label') {
  await drawEuLabel(euLabelDropdown.value, fontSize);
} else {
  // Draw a text label in the bottom-left corner.
  const labels = {
    generated: "🔺 Generated by AI",
    free: freeInput.value,
  };
  const label = labels[selectedOption];
  ctx.font = `${fontSize}px Arial`;
  ctx.fillStyle = 'white';
  ctx.strokeStyle = 'black';
  ctx.lineWidth = 2;
  ctx.strokeText(label, fontSize, canvas.height - fontSize);
  ctx.fillText(label, fontSize, canvas.height - fontSize);
}

// Steganography.
const secretText = document.getElementById('hiddenPrompt').value;
if (secretText.length > 0) {
  const imageData = ctx.getImageData(0, 0, canvas.width, canvas.height);
  const data = imageData.data;

  const binary = [...unescape(encodeURIComponent(secretText))]
    .map(char => char.charCodeAt().toString(2).padStart(8, '0'))
    .join('') + '00000000'; // add null terminator

  const maxLen = Math.floor(data.length / 4); // One byte per pixel alpha
  if (binary.length > maxLen) {
    alert("Message too long to encode in this image.");
    return;
  }

  for (let i = 0; i < binary.length; i++) {
    const alphaIndex = i * 4 + 3;
    const originalAlpha = data[alphaIndex];
    const bit = binary[i];
    data[alphaIndex] = (originalAlpha & 0b11111110) | parseInt(bit);
  }
  ctx.putImageData(imageData, 0, 0);
}

// Always place image on clipboard.
copyCanvasImageToClipboard(canvas);

});

// Clear button.
document.getElementById('clearButton').addEventListener('click', () => {
  if (originalImageSrc) {
    loadImageFromURL(originalImageSrc);
  } else {
    placeholderText.classList.remove('d-none');
    canvas.classList.add('d-none');
    ctx.clearRect(0, 0, canvas.width, canvas.height);
  }
});

